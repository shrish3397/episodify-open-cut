"""Exporters for episodic cuts to standard video chapter formats."""

from __future__ import annotations

from typing import Union
from pathlib import Path

from eoc.models import Recipe, seconds_to_timestamp


def export_ffmpeg_metadata(recipe: Recipe) -> str:
    """Generate FFmpeg FFMETADATA chapter file content."""
    lines = [
        ";FFMETADATA1",
        f"title={recipe.meta.title} ({recipe.meta.year}) [Episodify Open Cut]",
        f"comment=Generated by Episodify Open Cut ({recipe.total_episodes} Episodes)",
        "",
    ]

    for ep in recipe.episodes:
        start_ms = int(ep.start_seconds * 1000)
        end_ms = int(ep.end_seconds * 1000)
        lines.extend(
            [
                "[CHAPTER]",
                "TIMEBASE=1/1000",
                f"START={start_ms}",
                f"END={end_ms}",
                f"title=Episode {ep.episode_number}: {ep.title}",
                "",
            ]
        )

    return "\n".join(lines)


def export_mkv_xml(recipe: Recipe) -> str:
    """Generate MKVToolNix XML chapter markup."""
    lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<!DOCTYPE Chapters SYSTEM "matroskachapters.dtd">',
        "<Chapters>",
        "  <EditionEntry>",
        "    <EditionFlagDefault>1</EditionFlagDefault>",
    ]

    for ep in recipe.episodes:
        start_ts = seconds_to_timestamp(ep.start_seconds, include_millis=True) + "000000"
        end_ts = seconds_to_timestamp(ep.end_seconds, include_millis=True) + "000000"
        lines.extend(
            [
                "    <ChapterAtom>",
                f"      <ChapterTimeStart>{start_ts}</ChapterTimeStart>",
                f"      <ChapterTimeEnd>{end_ts}</ChapterTimeEnd>",
                "      <ChapterDisplay>",
                f"        <ChapterString>Episode {ep.episode_number}: {ep.title}</ChapterString>",
                "        <ChapterLanguage>eng</ChapterLanguage>",
                "      </ChapterDisplay>",
                "    </ChapterAtom>",
            ]
        )

    lines.extend(
        [
            "  </EditionEntry>",
            "</Chapters>",
        ]
    )
    return "\n".join(lines)


def export_chapter_srt(recipe: Recipe) -> str:
    """Generate SRT file containing chapter title title-cards at episode boundaries."""
    blocks = []
    for ep in recipe.episodes:
        # Display chapter card for first 15 seconds of episode
        card_end = min(ep.start_seconds + 15.0, ep.end_seconds)
        start_ts = seconds_to_timestamp(ep.start_seconds, include_millis=True).replace(".", ",")
        end_ts = seconds_to_timestamp(card_end, include_millis=True).replace(".", ",")

        block = (
            f"{ep.episode_number}\n"
            f"{start_ts} --> {end_ts}\n"
            f"[ Episode {ep.episode_number}: {ep.title} ]\n"
            f"{ep.recap_text}"
        )
        blocks.append(block)

    return "\n\n".join(blocks)
